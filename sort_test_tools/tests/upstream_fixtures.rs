// Expected hashes generated from the pinned, original upstream patterns.rs.
// Retained for patterns whose sampling sequence is unchanged with a fresh seeded RNG.
// The fixed-value shuffle reference uses the historical seeded StdRng adaptation.
// Fixtures retain the original benchmark u64 encoding; encode returned i32 values
// only here to compare against the independently generated upstream hashes.
// FNV-1a over each encoded u64's little-endian bytes.
#![cfg(all(target_arch = "x86_64", target_os = "linux", target_env = "gnu"))]
use rand::{rngs::StdRng, SeedableRng};
use sort_test_tools::generate;

#[test]
#[cfg(target_arch = "x86_64")]
fn matches_pinned_upstream_fixtures() {
    assert_eq!(FIXTURES.len(), 171);
    for &(pattern, len, seed, expected) in FIXTURES {
        let mut rng = StdRng::seed_from_u64(seed);
        let mut actual = 0xcbf29ce484222325_u64;
        for value in generate(pattern, len, &mut rng).unwrap() {
            let encoded = ((value as i64 + 2_147_483_648) as u64) * 2_147_483_647;
            for byte in encoded.to_le_bytes() {
                actual ^= byte as u64;
                actual = actual.wrapping_mul(0x100000001b3);
            }
        }
        assert_eq!(actual, expected, "{pattern}/{len}/{seed}");
    }
}

